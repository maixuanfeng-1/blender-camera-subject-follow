const nodes = [...document.querySelectorAll('[data-i18n]')];
const chinese = new Map(nodes.map(node => [node, node.innerHTML]));
const button = document.getElementById('language');
let english = false;
function setLanguage(value) {
  english = value;
  for (const node of nodes) node.innerHTML = english ? translations[node.dataset.i18n] : chinese.get(node);
  document.documentElement.lang = english ? 'en' : 'zh-CN';
  button.textContent = english ? '中文' : 'English';
  document.title = english ? 'Blender Camera Subject Follow — Free editable camera paths' : 'Blender Camera Subject Follow — 免费贝塞尔运镜与相机跟随';
  const video = document.querySelector('video');
  const source = video.querySelector('source');
  const filename = english ? 'camera-follow-demo.en.mp4' : 'camera-follow-demo.zh-CN.mp4';
  if (!source.getAttribute('src').endsWith(filename)) {
    source.setAttribute('src', 'media/' + filename);
    video.load();
  }
}
button.addEventListener('click', () => setLanguage(!english));
if (new URLSearchParams(location.search).get('lang') === 'en') setLanguage(true);
